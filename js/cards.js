// Helper schema functions
function getCardDef(cardId) {
    return cards[cardId] || null;
}

function isMonsterCard(cardId) {
    var c = getCardDef(cardId);
    return c && c.type === 'monsters';
}

function isSpellCard(cardId) {
    var c = getCardDef(cardId);
    return c && c.type === 'spells';
}

function isTrapCard(cardId) {
    var c = getCardDef(cardId);
    return c && c.type === 'traps';
}